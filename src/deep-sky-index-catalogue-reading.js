export function indexCatalogueRecord(number) {
  const observer = groups[Math.floor(number / 100)]?.[number % 100];
  const page = pages.find(([lo, hi]) => number >= lo && number <= hi);
  return {
    observer: observer === '.' ? undefined : observer,
    pdfPage: page?.[2],
    printedPage: page?.[3],
  };
}
