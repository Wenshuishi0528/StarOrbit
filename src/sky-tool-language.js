export function skyText(key, params = {}, lang = getLanguage()) {
  const index = { zh: 0, en: 1, fr: 2, ru: 3 }[lang] ?? 1;
  return (words[key]?.[index] || key).replace(/\{(\w+)\}/g, (_, name) => params[name] ?? '');
}
