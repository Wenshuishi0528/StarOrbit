// Observation dates, right ascensions as printed, and selected visual features from
// Charles Messier, Catalogue des nébuleuses et des amas d’étoiles (1781).
// The dates are headed “date des observations”; they are not necessarily discovery dates.
// Each spread has dated positions on the left, observing notes on the right.
// These are the last entry numbers on successive spreads, pp. 228–267.
const lastOnSpread = [
  5, 10, 14, 20, 25, 31, 35, 42, 49, 53, 57, 62, 68, 71, 76, 80, 85, 92, 97, 103,
];
export function printedMessierSource(number) {
  if (!Number.isInteger(number) || number < 1 || number > 103) return undefined;
  const index = lastOnSpread.findIndex((last) => number <= last);
  const left = 228 + index * 2;
  return {
    name: 'C. Messier · 1781 · pp. ' + left + '–' + (left + 1),
    url:
      'https://www.digitale-sammlungen.de/en/view/bsb10538209?page=' +
      (left + 8) +
      ',' +
      (left + 9),
  };
}

