      'planetary-nebula': { zh: '行星状星云', en: 'Planetary nebula' },
      'supernova-remnant': { zh: '超新星遗迹', en: 'Supernova remnant' },
      'asterism': { zh: '星群', en: 'Asterism' },
      'double-star': { zh: '光学双星', en: 'Optical double star' },
