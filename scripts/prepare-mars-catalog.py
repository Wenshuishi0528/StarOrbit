def main():
 path=CACHE/'names.zip'
 if not path.exists():
  r=requests.get(URL,timeout=90);r.raise_for_status();path.write_bytes(r.content)
 directory=CACHE/'names';directory.mkdir(exist_ok=True)
 with zipfile.ZipFile(path) as z:z.extractall(directory)
 reader=shapefile.Reader(str(next(directory.glob('*.shp'))),encoding='utf-8')
 rows=[]
 for record in reader.iterRecords():
  d=record.as_dict(); name=d['name']
  if name not in NAMES:continue
  assert d['approval']=='Adopted by IAU'
  zh,description=NAMES[name]
  rows.append({'id':'iau-'+d['link'].rsplit('/',1)[-1],'name':zh,'nameZh':zh,'nameEn':name,'latitude':round(d['center_lat'],6),'longitude':round((d['center_lon']+180)%360-180,6),'type':'landform','featureType':d['code'],'diameterKm':round(d['diameter'],3),'description':description,'source':d['link'].replace('http:','https:')})
 assert len(rows)==len(NAMES),(len(rows),len(NAMES))
 rows.sort(key=lambda r:list(NAMES).index(r['nameEn']))
 landings=[{'id':id,'name':zh,'nameZh':zh,'nameEn':en,'latitude':lat,'longitude':lon,'type':'landing','country':country,'countryCN':country=='CN','landingDateUTC':date,'description':description,'source':source} for id,zh,en,lat,lon,date,country,source,description in LANDINGS]
