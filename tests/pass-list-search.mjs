import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { queryObservation } from '../src/observation-query.js';
const data = JSON.parse(readFileSync(new URL('./reference/css-20261109.json', import.meta.url)));
const site = { name:'北京', latitude:39.9042, longitude:116.4074, height:50 };
const start = Date.parse('2026-11-10T06:00:00Z'), end = Date.parse('2026-12-01T00:00:00Z');
const options = { list:true, end, daylight:'night', minimumPeakElevation:60 };
const list = await queryObservation(data, site, start, options);
assert.ok(list.passes.length > 2);
assert.ok(list.passes.every((p,i,a) => p.maximum.time>=start && p.maximum.time<end && p.maximum.elevation>=60 && p.maximum.sunElevation<0 && (!i || p.maximum.time>a[i-1].maximum.time+1000)));
const next = await queryObservation(data,site,start,{ direction:1, daylight:'night', minimumPeakElevation:60 });
assert.ok(Math.abs(next.passes[0].maximum.time-list.passes[0].maximum.time)<250);
const split = Math.floor(list.passes[1].maximum.time / 86400000) * 86400000;
const left = await queryObservation(data,site,start,{...options,end:split});
const right = await queryObservation(data,site,split,{...options});
assert.equal(left.passes.length+right.passes.length,list.passes.length);
assert.ok(right.passes[0].maximum.time>=split);
const visible = await queryObservation(data,site,start,{...options,visibleOnly:true});
assert.ok(visible.passes.length>0 && visible.passes.length<list.passes.length);
assert.ok(visible.passes.every(p=>p.maximum.illumination>0.01 && p.maximum.sunElevation < -6));
await assert.rejects(queryObservation(data,site,start,{...options,end:start}),/列表日期/);
const cancel = new AbortController();
await assert.rejects(queryObservation(data,site,start,{...options,signal:cancel.signal,onProgress:()=>cancel.abort()}),{name:'AbortError'});
console.log('Pass list: enumeration, next-search consistency, date boundary, visibility and cancellation passed',list.passes.map(p=>[new Date(p.maximum.time).toISOString(),p.maximum.elevation]));
