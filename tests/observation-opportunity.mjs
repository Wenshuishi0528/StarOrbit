import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {BEIJING_BALCONY,EXAMPLE_HORIZON} from '../src/balcony-lab-geometry.js';
import {createPassSampler,predictionSource,predictPasses} from '../src/pass-prediction.js';
import {durationClock,observationOpportunity,preferredOpportunity,watchPhase} from '../src/observation-opportunity.js';
import {balconyRecord,readBalconyRecord,passFromRecord} from '../src/balcony-record.js';
import {siteHorizon} from '../src/observation-sites.js';
const point=t=>({time:t,azimuth:(350+t/1000)%360,elevation:12,illumination:1,sunElevation:-8});
const pass={start:0,end:20000,maximum:point(10000),rise:point(0),set:point(20000),path:[point(0),point(10000),point(20000)],visible:[{start:0,end:20000}]};
const profile=[[1,20],[3.8,20],[4,0],[4.2,20],[7,20],[8,0],[350,0],[351,20]];
const split=observationOpportunity(pass,point,profile);
assert.equal(split.windows.length,3);
assert.equal(split.windows[1].startReason,'roof');assert.equal(split.windows[1].endReason,'roof');
assert.ok(split.windows[1].end-split.windows[1].start<500,'narrow skyline gap resolved across 0° azimuth');
assert.equal(watchPhase(split,split.windows[1].start-100).phase,'waiting');
assert.equal(watchPhase(split,split.windows[1].start+10).phase,'observing');
assert.equal(watchPhase(split,20001).phase,'ended');
assert.equal(watchPhase(split,0,split.windows[1].start).window,split.windows[1]);
assert.equal(observationOpportunity(pass,point,[[0,90]]).reason,'roof');
assert.equal(observationOpportunity({...pass,visible:[],path:[{...point(0),sunElevation:2}]},point).reason,'twilight');
assert.equal(observationOpportunity({...pass,visible:[],path:[{...point(0),illumination:0}]},point).reason,'shadow');
assert.equal(preferredOpportunity([{windows:[]},split],8000),1);assert.equal(durationClock(3599990),'1:00:00');
const data={...JSON.parse(readFileSync('assets/orbit.json')),missionId:'tiangong'},source=predictionSource(data),sample=createPassSampler(source,BEIJING_BALCONY);
const {passes}=await predictPasses(data,BEIJING_BALCONY,source.recordStart,48,{minimumElevation:10});
const models=passes.map(p=>observationOpportunity(p,sample,EXAMPLE_HORIZON)),index=preferredOpportunity(models,source.recordStart),real=models[index],p=passes[index];
assert.ok(real.duration>0&&real.duration<=p.end-p.start);assert.ok(real.windows.every(w=>w.peak.time>=w.start&&w.peak.time<=w.end));
assert.ok(models.some(m=>m.windows.some(w=>w.startReason==='roof'||w.endReason==='roof')));
const saved=balconyRecord({site:BEIJING_BALCONY,profile:EXAMPLE_HORIZON,profileKind:'example',missionId:'tiangong',time:p.maximum.time,minimumElevation:10,pass:p,data,source});
assert.equal(saved.orbit,data);assert.equal(readBalconyRecord(saved.record).profileKind,'example');
const restored=passFromRecord(saved.record,source,sample);assert.deepEqual(restored.visible,p.visible);assert.equal(restored.start,p.start);
assert.deepEqual(observationOpportunity(restored,sample,EXAMPLE_HORIZON).windows.map(w=>[w.start,w.end]),real.windows.map(w=>[w.start,w.end]));
assert.throws(()=>passFromRecord({...saved.record,passMaximum:p.end+5000},source,sample));
assert.equal(siteHorizon(BEIJING_BALCONY,true,new Map()).kind,'example');assert.equal(siteHorizon(BEIJING_BALCONY,false,new Map()).kind,'flat');
console.log('Observation windows: 0° seam and subsecond building gap, optical/roof boundaries, in-window peaks, watch phases, exact archived pass.');
