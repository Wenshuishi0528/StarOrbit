async page=>{
 await page.setViewportSize({width:1280,height:860});
 await page.waitForFunction(()=>window.viewer?.sim.initialized);
 if(await page.locator('#welcomeDialog').evaluate(el=>el.open))await page.locator('#skipTour').click();
 if(await page.locator('#flightLab').evaluate(el=>el.open))await page.locator('#closeFlightLab').click();
 await page.locator('#languageZh').click();
 await page.locator('#openFlightLab').click();
 const tabs=await page.locator('.flight-lab-tabs > [role=tab]').allTextContents();
 if(tabs.join('/')!=='过境预报/交会对接/轨道长曝光/阳台观测/巡天拍摄计划')throw Error('Unexpected Mission Lab navigation '+tabs);
 const mainClock=await page.evaluate(()=>viewer.sim.time);
 await page.locator('#passTab').click();
 await page.getByRole('button',{name:'使用有效数据时段',exact:true}).click();
 await page.locator('#passPanel [data-action=predict]').click();
 const slider=page.locator('[data-testid=pass-time-slider]');await slider.waitFor({state:'visible'});await slider.press('Home');
 const chosenTime=await page.locator('.pass-readout-time').getAttribute('datetime');
 await page.getByRole('button',{name:'在阳台观测',exact:true}).click();
 const balcony=page.locator('#balconyPanel');const balconyClock=balcony.locator('[data-id=clock]');
 if(await balconyClock.getAttribute('datetime')!==chosenTime)throw Error('Pass handoff changed the chosen time');
 await balcony.locator('[data-id=demo]').click();
 await page.waitForFunction(()=>{const list=document.querySelector('#balconyPanel [data-id=passes]');return !list.disabled&&list.options.length>1;});
 const sky=balcony.locator('[data-id=sky]');await sky.waitFor({state:'visible'});
 const groundSlider=balcony.locator('[data-id=scrub]');await groundSlider.press('Home');
 const begin=await balconyClock.getAttribute('datetime');await groundSlider.press('End');
 if(begin===await balconyClock.getAttribute('datetime'))throw Error('Balcony clock did not follow the slider');
 await page.locator('#surveyTab').click();
 const survey=page.locator('#surveyPanel'),play=survey.locator('[data-survey=play]');
 await survey.locator('[data-survey=example]').click();
 const alternative=survey.locator('[data-survey=alternative]');
 if(await alternative.isVisible())await alternative.click();
 if(!await play.isEnabled())throw Error('Example plan is blocked');
 await survey.locator('[data-survey=challenge]').click();if(await play.isEnabled())throw Error('Conflict allowed execution');
 await survey.locator('[data-survey=example]').click();
 const clock=survey.locator('[data-survey=clock]');await clock.press('End');
 if(await survey.locator('[data-state=covered]').count()!==4)throw Error('Four completed fields were not displayed');
 await clock.press('Home');await play.click();
 await page.waitForFunction(()=>Number(document.querySelector('[data-survey=clock]').value)>1);
 await page.locator('#balconyTab').click();const paused=await clock.inputValue();
 await page.locator('#surveyTab').click();
 if(await clock.inputValue()!==paused)throw Error('Survey time advanced after leaving');
 if(await page.evaluate(()=>viewer.sim.time)!==mainClock)throw Error('Lab altered the main clock');
 await page.locator('#closeFlightLab').click();
 return {tabs,passTime:chosenTime,coveredFields:4,paused:true};
}
