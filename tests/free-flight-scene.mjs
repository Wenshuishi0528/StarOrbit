import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Quaternion,Vector3} from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {createFreeFlightScene,freeFlightViewport} from '../src/free-flight-scene.js';

// Arbitrarily moved panels must not become fixed left/right reservations.
const free=freeFlightViewport(1200,800,[{left:700,right:1006,top:16,bottom:560,width:306,height:544},
 {left:8,right:260,top:400,bottom:790,width:252,height:390}]);
assert(free.right<=690/1200&&free.left>=270/1200,'moved controls and instruments leave an actually clear camera viewport');
const covered=freeFlightViewport(400,600,[{left:0,right:400,top:0,bottom:600,width:400,height:600}]);
assert(covered.right>covered.left&&covered.bottom>covered.top,'a fully covered view still has finite optics');

// Exercise real model/camera transforms without a GPU or a second renderer.
const meta=JSON.parse(fs.readFileSync('assets/model.json'));
const bytes=fs.readFileSync('assets/station.glb');
const gltf=await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
const templates=Object.fromEntries(Object.keys(meta.modules).map(type=>[type,gltf.scene.getObjectByName('module_'+type)]));
let width=1440,height=900,mobile=false;
const panel={getBoundingClientRect:()=>mobile?{left:10,right:380,top:500,bottom:780,width:370,height:280}:{left:12,right:318,top:12,bottom:700,width:306,height:688}};
const stack={getBoundingClientRect:()=>mobile?{left:208,right:382,top:8,bottom:420,width:174,height:412}:{left:1172,right:1424,top:16,bottom:884,width:252,height:868}};
const instruments={hidden:true,querySelector:selector=>selector==='.ffi-stack'?stack:null};
const documentStub=Object.assign(new EventTarget(),{getElementById:id=>id==='freeFlightPanel'?panel:id==='freeFlightInstruments'?instruments:null});
globalThis.document=documentStub;
const canvas=Object.assign(new EventTarget(),{style:{},getRootNode:()=>documentStub});
const stage={get clientWidth(){return width;},get clientHeight(){return height;},getBoundingClientRect:()=>({left:0,top:0,right:width,bottom:height,width,height})};
let rendered;
const renderer={domElement:canvas,autoClear:true,state:{buffers:{depth:{setMask(){}}}},clearDepth(){},render:scene=>{rendered=scene;}};
const flight=createFreeFlightScene({api:{renderer,stage}},{templates,meta},{slots:{TH_WENTIAN:'WT',TH_MENGTIAN:'MT',TH_FORWARD:'SZ',TH_AFT:'TZ'}});
const [sz,tz]=['SZ','TZ'].map(type=>flight.definitions.find(d=>d.type===type));
const offset=(definition,distance)=>({...definition,status:'free',position:new Vector3(...definition.position)
 .add(new Vector3(distance,0,0).applyQuaternion(new Quaternion(...definition.quaternion))).toArray()});
let states=[offset(sz,12),offset(tz,12)];
flight.update(states,sz.id);flight.setView('onboard');flight.update(states,sz.id);flight.draw();
assert.equal(rendered.getObjectByName(sz.id).visible,false);
assert.equal(rendered.getObjectByName(tz.id).visible,true);
flight.update(states,tz.id);flight.draw();
assert.equal(rendered.getObjectByName(sz.id).visible,true,'previous ship must return when switching onboard control');
assert.equal(rendered.getObjectByName(tz.id).visible,false,'onboard camera hides only its own ship');
let projection=flight.getDockingProjection();
assert(projection.visible&&!projection.behind);
assert(Math.abs(projection.forwardDistance-12)<1e-6);
assert(Math.abs(projection.x-projection.bore.x)<1e-8&&Math.abs(projection.y-projection.bore.y)<1e-8,'aligned target and optical crosshair coincide');
assert(projection.bore.x>0,'desktop dock camera optical axis stays clear of the left panel');
const hiddenBore=projection.bore.x;
instruments.hidden=false;flight.update(states,tz.id);projection=flight.getDockingProjection();
assert(projection.bore.x<hiddenBore,'visible HUD moves the optical axis left into the remaining clear space');
assert(projection.bounds.right<.7&&projection.bounds.left>-.6,'HUD and controls both reserve camera space');
assert(projection.x>projection.bounds.left&&projection.x<projection.bounds.right);
instruments.hidden=true;flight.update(states,tz.id);projection=flight.getDockingProjection();
assert(Math.abs(projection.bore.x-hiddenBore)<1e-9,'hiding all instruments restores the wider camera area');
instruments.hidden=false;flight.update(states,tz.id);
states[1]={...states[1],position:new Vector3(...states[1].position).add(new Vector3(0,2,0).applyQuaternion(new Quaternion(...tz.quaternion))).toArray()};
flight.update(states,tz.id);projection=flight.getDockingProjection();
assert(projection.x<projection.bore.x,'moving the ship right moves the fixed host port left in the image');
states[1]={...states[1],quaternion:new Quaternion(...tz.quaternion).multiply(new Quaternion().setFromAxisAngle(new Vector3(0,0,1),Math.PI)).toArray()};
flight.update(states,tz.id);projection=flight.getDockingProjection();
assert(projection.behind&&!projection.visible,'turned-away port is marked behind, never drawn as a front target');
states=[offset(sz,10000),offset(tz,12)];
flight.setView('external');flight.update(states,sz.id);flight.update(states,tz.id);flight.draw();
assert(flight.camera.position.length()<300,'distant uncontrolled ship must not pull a selected dock camera kilometres away');
assert.equal(rendered.getObjectByName(sz.id).visible,true);
assert.equal(rendered.getObjectByName(tz.id).visible,true);
const shipScreen=new Vector3(...states[1].position).project(flight.camera);
projection=flight.getDockingProjection();
assert(shipScreen.x>projection.bounds.left&&shipScreen.x<projection.bounds.right,'external fit keeps the selected spacecraft between both control panels');
// Exterior focus is independent of the pilot, with whole-formation framing
// opt-in. Exercise real CAD bounds and translation tracking, not mocked math.
assert.equal(flight.cameraTarget,'active');
const activeEye=flight.camera.position.clone();
flight.setCameraTarget('ship:'+sz.id);
assert.equal(flight.cameraTarget,'ship:'+sz.id);
assert(flight.camera.position.distanceTo(new Vector3(...states[0].position))<100,'fixed far ship receives a close exterior view');
const farEye=flight.camera.position.clone();
flight.update(states,sz.id);
flight.update(states,tz.id);
assert(flight.camera.position.distanceTo(farEye)<1e-8,'changing pilot leaves a fixed camera target untouched');
states[0]={...states[0],position:new Vector3(...states[0].position).add(new Vector3(7,11,-2)).toArray()};
flight.update(states,tz.id);
assert(flight.camera.position.clone().sub(farEye).distanceTo(new Vector3(7,11,-2))<1e-8,'camera follows its own target translation');
flight.setCameraTarget('station');
const stationEye=flight.camera.position.clone();
assert(stationEye.length()<300,'station framing excludes a distant departing ship');
states[1]={...states[1],position:new Vector3(...states[1].position).add(new Vector3(6,3,2)).toArray()};
flight.update(states,tz.id);
assert(flight.camera.position.distanceTo(stationEye)<1e-8,'station camera does not follow the controlled ship');
flight.setCameraTarget('all');
assert(flight.camera.position.length()>1000,'explicit whole-formation view includes the distant ship');
const allEye=flight.camera.position.clone();
flight.update(states,sz.id);flight.update(states,tz.id);
assert(flight.camera.position.distanceTo(allEye)<1e-8,'whole-formation camera does not jump when pilot changes');
flight.setCameraTarget('ship:'+sz.id);
flight.setView('onboard');flight.update(states,tz.id);
const onboardEye=flight.camera.position.clone();
flight.setCameraTarget('station');flight.update(states,tz.id);
assert(flight.camera.position.distanceTo(onboardEye)<1e-8,'exterior focus cannot change docking camera ownership');
flight.setCameraTarget('unknown');
assert.equal(flight.cameraTarget,'active','unknown saved target falls back to current pilot');
// Restore the aligned port case for the mobile camera checks below.
states=[offset(sz,10000),offset(tz,12)];flight.update(states,tz.id);
mobile=true;width=390;height=780;flight.setView('onboard');flight.update(states,tz.id);
projection=flight.getDockingProjection();
assert(Math.abs(projection.aspect-.5)<1e-12);
assert(projection.bore.y>0,'mobile optical axis stays above the bottom sheet');
assert(projection.bore.x<-.4,'mobile optical axis stays to the left of the instrument stack');
assert((projection.bore.x+1)*width/2+32<stack.getBoundingClientRect().left,'64px reticle does not overlap the mobile instruments');
assert(projection.bounds.bottom>-.4&&projection.bounds.right<.1);
assert(projection.visible&&Math.abs(projection.x-projection.bore.x)<1e-8&&Math.abs(projection.y-projection.bore.y)<1e-8);
flight.dispose();flight.dispose();
console.log('Free flight camera: independent exterior targets, all-view opt-in, pilot-independent fixed focus, both-way craft switch, hidden own model, distant inactive craft, panel-aware optical projection and mobile resize pass.');
